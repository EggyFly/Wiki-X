package i18n

import "strings"

var catalogs = map[string]map[string]string{
	"zh-CN": zhCN,
	"en":    en,
}

func Normalize(lang string) string {
	lang = strings.ToLower(strings.TrimSpace(lang))
	if strings.HasPrefix(lang, "zh") {
		return "zh-CN"
	}
	if strings.HasPrefix(lang, "en") {
		return "en"
	}
	return "zh-CN"
}

func For(lang string) map[string]string {
	if catalog, ok := catalogs[Normalize(lang)]; ok {
		return catalog
	}
	return zhCN
}

func Text(lang, key string) string {
	return For(lang)[key]
}

func Message(lang, text string) string {
	if text == "" || Normalize(lang) == "zh-CN" {
		return text
	}
	if translated, ok := englishMessages[text]; ok {
		return translated
	}
	return text
}

